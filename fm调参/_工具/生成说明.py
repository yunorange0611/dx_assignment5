def table(headers, rows):
    return '<table><tr>'+''.join('<th>'+h+'</th>' for h in headers)+'</tr>'+''.join('<tr>'+''.join('<td>'+v+'</td>' for v in row)+'</tr>' for row in rows)+'</table>'


def page(title, body):
    return '<h1>'+title+'</h1>'+body


def pdf(filename, pages):
    doc=fitz.open()
    for section in pages:
        story=fitz.Story('<html><body>'+section+'</body></html>',user_css=CSS,archive=ARCHIVE)
        part=story.write_with_links(lambda number,filled:(fitz.Rect(0,0,595,842),fitz.Rect(44,46,551,789),None))
        doc.insert_pdf(part)
        part.close()
    for i,p in enumerate(doc):
        p.draw_line((44,806),(551,806),color=(.7,.78,.82),width=.5)
        p.insert_text((44,820),'RM / '+filename.split('_')[0]+' / '+str(i+1)+' of '+str(len(doc)),fontsize=8,color=(.25,.35,.4))
    doc.set_metadata(dict(title=filename.removesuffix('.pdf'),author='工程车电控协作',subject='与当前源码及FreeMASTER中文分组配套；软件已检查，实物待验'))
    path=ROOT/filename
    doc.subset_fonts()
    doc.save(path,garbage=4,deflate=True)
    print(f'{filename}: {len(doc)} pages')
    doc.close()


